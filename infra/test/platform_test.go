// Full-stack tier: apply the platform fixture (cluster + Argo CD + root app),
// wait for every Argo CD Application to be Synced and Healthy, destroy.
// ~40 minutes. It doubles as the demo-day rehearsal. Same SKIP_* stages as above.

// Applications that must exist: the root, the children from deploy/platform,
// and the apps the mos-services ApplicationSet generates (one per service).
var requiredApps = []string{
	"root",
	"strimzi-operator", "cnpg-operator", "kube-prometheus-stack",
	"mos-kafka", "mos-postgres", "mos-observability",
	"ledger-api", "bill-scheduler",
}

type argoApps struct {
	Items []struct {
		Metadata struct{ Name string }
		Status   struct {
			Sync   struct{ Status string }
			Health struct{ Status string }
		}
	}
}

func TestPlatformBootstrap(t *testing.T) {
	project := projectID(t)

	defer test_structure.RunTestStage(t, "teardown", func() {
		opts := test_structure.LoadTerraformOptions(t, platformDir)
		// Deleting a cluster does not delete the disks behind its PVCs, so remove
		// the workloads first and remember which disks to look for afterwards.
		pvs := preDestroy(t, project, opts)
		terraform.DestroyContext(t, context.Background(), opts)
		assertNoLeftoverDisks(t, project, pvs)
	})

	test_structure.RunTestStage(t, "setup", func() {
		opts := fixtureOptions(project, uniqueSuffix(), platformDir, []string{myCIDR(t)})
		test_structure.SaveTerraformOptions(t, platformDir, opts)
		terraform.InitAndApplyContext(t, t.Context(), opts)
	})

	test_structure.RunTestStage(t, "validate", func() {
		opts := test_structure.LoadTerraformOptions(t, platformDir)
		kopts := k8s.NewKubectlOptions("", kubeconfigFor(t, project, opts).ConfigPath, "argocd")

		// 60 x 30s = 30 minutes.
		retry.DoWithRetryContext(t, t.Context(), "all Argo CD apps Synced and Healthy", 60, 30*time.Second, func() (string, error) {
			out, err := k8s.RunKubectlAndGetOutputContextE(t, t.Context(), kopts, "get", "applications.argoproj.io", "-o", "json")
			if err != nil {
				return "", err
			}
			return "", checkApps(out)
		})
	})
}

// checkApps returns an error naming whatever is not ready yet.
func checkApps(kubectlJSON string) error {
	var apps argoApps
	if err := json.Unmarshal([]byte(kubectlJSON), &apps); err != nil {
		return err
	}
	state := map[string]string{}
	for _, a := range apps.Items {
		state[a.Metadata.Name] = a.Status.Sync.Status + "/" + a.Status.Health.Status
	}
	var waiting []string
	for _, name := range requiredApps {
		if state[name] != "Synced/Healthy" {
			waiting = append(waiting, fmt.Sprintf("%s=%q", name, state[name]))
		}
	}
	// Apps generated by the ApplicationSet (one per service) must be green too.
	for name, s := range state {
		if s != "Synced/Healthy" {
			waiting = append(waiting, fmt.Sprintf("%s=%q", name, s))
		}
	}
	if len(waiting) > 0 {
		return fmt.Errorf("not ready: %s", strings.Join(waiting, ", "))
	}
	return nil
}

// preDestroy removes everything that owns a disk and returns the names of the
// PersistentVolumes (they are the disk names on GKE). Failures are logged, not
// fatal: destroy must still run.
func preDestroy(t *testing.T, project string, opts *terraform.Options) []string {
	t.Helper()
	ctx := context.Background()
	kopts := k8s.NewKubectlOptions("", kubeconfigFor(t, project, opts).ConfigPath, "argocd")

	pvOut, _ := k8s.RunKubectlAndGetOutputContextE(t, ctx, kopts, "get", "pv", "-o", "jsonpath={.items[*].metadata.name}")
	pvs := strings.Fields(pvOut)

	// Order matters. Delete whatever would recreate things first (root app, then
	// the ApplicationSet, then the child apps), then the namespace that holds
	// the pods and PVCs, and so the disks.
	for _, args := range [][]string{
		{"delete", "application", "root"},
		{"delete", "applicationset", "--all"},
		{"delete", "application", "--all"},
		{"delete", "namespace", "mos"},
	} {
		_ = k8s.RunKubectlContextE(t, ctx, kopts, append(args, "--wait=true", "--timeout=10m")...)
	}
	return pvs
}

// After destroy, none of the cluster's PV disks may remain.
func assertNoLeftoverDisks(t *testing.T, project string, pvs []string) {
	t.Helper()
	if len(pvs) == 0 {
		return
	}
	out, err := shell.RunCommandContextAndGetStdOutE(t, context.Background(), &shell.Command{
		Command: "gcloud",
		Args: []string{"compute", "disks", "list", "--project", project,
			"--filter", "name:(" + strings.Join(pvs, " OR ") + ")", "--format", "value(name)"},
	})
	require.NoError(t, err)
	require.Empty(t, strings.TrimSpace(out), "persistent disks left behind: delete them with `gcloud compute disks delete`")
}
